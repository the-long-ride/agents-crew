import { readFile, writeFile } from 'node:fs/promises';
const pkg = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8'));
const repository = process.env.AGENTS_CREW_GITHUB_REPOSITORY ?? '';
await writeFile(new URL('../src/generated.ts', import.meta.url), `// Generated by scripts/write-build-metadata.mjs\nexport const INSTALLER_VERSION = ${JSON.stringify(pkg.version)};\nexport const DEFAULT_GITHUB_REPOSITORY = ${JSON.stringify(repository)};\n`);
